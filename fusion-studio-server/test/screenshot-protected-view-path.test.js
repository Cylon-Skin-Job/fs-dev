'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');

describe('screenshot generated-file protected view boundary', () => {
  let root;
  let canonicalRoot;
  let sourceScreenshot;
  let consoleErrorSpy;
  let consoleWarnSpy;

  beforeEach(() => {
    jest.resetModules();
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'fusion-screenshot-protection-'));
    process.env.FUSION_LOCAL_MACHINE = 'Test-Machine';
    process.env.FUSION_FOCUS_STATE_PATH = path.join(root, 'focus.json');
    fs.writeFileSync(process.env.FUSION_FOCUS_STATE_PATH, '{"focused":true}', 'utf8');
    canonicalRoot = path.join(root, 'ai', 'Test-Machine', 'System', 'Views', '001-files');
    fs.mkdirSync(canonicalRoot, { recursive: true });
    fs.writeFileSync(path.join(canonicalRoot, 'content.json'), 'protected', 'utf8');
    const screenshotParent = path.join(root, 'ai', 'Test-Machine', 'Data');
    fs.mkdirSync(screenshotParent, { recursive: true });
    fs.symlinkSync(canonicalRoot, path.join(screenshotParent, 'Screenshots'), 'dir');
    sourceScreenshot = path.join(root, 'Screenshot Test.png');
    fs.writeFileSync(sourceScreenshot, 'image', 'utf8');

    jest.doMock('../lib/workspace/workspace-controller', () => ({
      getActiveWorkspaceSync: jest.fn(() => ({
        id: 'workspace-a', repo_path: root,
      })),
      listWorkspaces: jest.fn(async () => []),
    }));
    jest.doMock('../lib/screenshot/source-folder-service', () => ({
      refresh: jest.fn(async () => null),
      get: jest.fn(async () => null),
    }));
    jest.doMock('../lib/watch/core', () => ({
      subscribe: jest.fn(),
      unsubscribe: jest.fn(),
    }));
    consoleErrorSpy = jest.spyOn(console, 'error').mockImplementation(() => {});
    consoleWarnSpy = jest.spyOn(console, 'warn').mockImplementation(() => {});
  });

  afterEach(() => {
    consoleErrorSpy.mockRestore();
    consoleWarnSpy.mockRestore();
    delete process.env.FUSION_LOCAL_MACHINE;
    delete process.env.FUSION_FOCUS_STATE_PATH;
    fs.rmSync(root, { recursive: true, force: true });
    jest.resetModules();
  });

  test('public file capture denies a symlink alias before writing generated bytes', async () => {
    const createScreenshotHandlers = require('../lib/screenshot/ws-handlers');
    const ws = {
      sent: [],
      send(message) { this.sent.push(JSON.parse(message)); },
    };
    const handlers = createScreenshotHandlers({ getAllClients: () => [] });

    await handlers['screenshot:file-capture'](ws, {
      type: 'screenshot:file-capture',
      workspaceId: 'workspace-a',
      requestId: 'protected-capture',
      dataUrl: 'data:image/png;base64,aW1hZ2U=',
    });

    expect(fs.readdirSync(canonicalRoot)).toEqual(['content.json']);
    expect(ws.sent).toEqual([expect.objectContaining({
      type: 'screenshot:error', requestId: 'protected-capture',
    })]);
  });

  test('hotkey copy denies a symlink alias before copying generated bytes', async () => {
    const watcher = require('../lib/screenshot/hotkey-screenshot-watcher');

    await expect(watcher.copyToWorkspace(sourceScreenshot)).rejects.toMatchObject({
      code: 'PROTECTED_VIEW_PATH',
    });

    expect(fs.readdirSync(canonicalRoot)).toEqual(['content.json']);
  });

  test('ordinary generated screenshot destinations remain functional', async () => {
    const screenshotDir = path.join(root, 'ai', 'Test-Machine', 'Data', 'Screenshots');
    fs.unlinkSync(screenshotDir);
    fs.mkdirSync(screenshotDir);
    const createScreenshotHandlers = require('../lib/screenshot/ws-handlers');
    const watcher = require('../lib/screenshot/hotkey-screenshot-watcher');
    const ws = {
      sent: [],
      send(message) { this.sent.push(JSON.parse(message)); },
    };

    await createScreenshotHandlers({ getAllClients: () => [] })['screenshot:file-capture'](ws, {
      type: 'screenshot:file-capture',
      workspaceId: 'workspace-a',
      dataUrl: 'data:image/png;base64,aW1hZ2U=',
    });
    await watcher.copyToWorkspace(sourceScreenshot);

    expect(ws.sent).toEqual([expect.objectContaining({ type: 'screenshot:file-captured' })]);
    expect(fs.readdirSync(screenshotDir)).toEqual(expect.arrayContaining([
      'Screenshot Test.png',
      expect.stringMatching(/^fusion-capture-.*\.png$/),
    ]));
  });

  test('public file capture denies a broken final symlink into a protected tree', async () => {
    jest.useFakeTimers().setSystemTime(Date.parse('2026-01-02T03:04:05Z'));
    try {
      const screenshotDir = path.join(root, 'ai', 'Test-Machine', 'Data', 'Screenshots');
      fs.unlinkSync(screenshotDir);
      fs.mkdirSync(screenshotDir);
      const generatedPath = path.join(screenshotDir, 'fusion-capture-2026-01-02T03-04-05-000Z.png');
      const protectedFutureFile = path.join(canonicalRoot, 'future.png');
      fs.symlinkSync(protectedFutureFile, generatedPath);
      const createScreenshotHandlers = require('../lib/screenshot/ws-handlers');
      const ws = {
        sent: [],
        send(message) { this.sent.push(JSON.parse(message)); },
      };

      await createScreenshotHandlers({ getAllClients: () => [] })['screenshot:file-capture'](ws, {
        type: 'screenshot:file-capture',
        workspaceId: 'workspace-a',
        dataUrl: 'data:image/png;base64,aW1hZ2U=',
      });

      expect(fs.lstatSync(generatedPath).isSymbolicLink()).toBe(true);
      expect(fs.existsSync(protectedFutureFile)).toBe(false);
      expect(ws.sent).toEqual([expect.objectContaining({ type: 'screenshot:error' })]);
    } finally {
      jest.useRealTimers();
    }
  });
});
